/** Call with `true` right before opening a native file/folder picker and
 * `false` once it closes, so the popover window doesn't hide itself when
 * the OS panel steals focus (see the Rust-side `tray::SUPPRESS_HIDE`). */
export function setSuppressHide(suppressed: boolean): Promise<void> {
  return call("set_suppress_hide", { suppressed });
}
